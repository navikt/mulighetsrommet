    Artskontokode.TILRETTELAGT_ARBEID_ORDINAER -> Artskonto.TILRETTELAGT_ARBEID_ORDINAER
    Artskontokode.ARBEIDSMARKEDSOPPLAERING -> Artskonto.ARBEIDSMARKEDSOPPLAERING
